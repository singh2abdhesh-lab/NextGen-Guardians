package com.enterprise.ai.common.dto;

import com.fasterxml.jackson.annotation.JsonInclude;
import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.NotBlank;

@JsonInclude(JsonInclude.Include.NON_NULL)
@Schema(description = "Payload submitted to Response Quality Checker for verification")
public class QualityCheckRequest {

    @Schema(description = "Unique correlation request ID", example = "req-10293")
    private String requestId;

    @NotBlank(message = "Prompt context cannot be blank")
    @Schema(description = "Input prompt used to generate the completion", requiredMode = Schema.RequiredMode.REQUIRED)
    private String prompt;

    @NotBlank(message = "Response payload cannot be blank")
    @Schema(description = "Raw completion generated by upstream LLM", requiredMode = Schema.RequiredMode.REQUIRED)
    private String response;

    public QualityCheckRequest() {
    }

    public QualityCheckRequest(String requestId, String prompt, String response) {
        this.requestId = requestId;
        this.prompt = prompt;
        this.response = response;
    }

    public static QualityCheckRequestBuilder builder() {
        return new QualityCheckRequestBuilder();
    }

    public String getRequestId() {
        return requestId;
    }

    public void setRequestId(String requestId) {
        this.requestId = requestId;
    }

    public String getPrompt() {
        return prompt;
    }

    public void setPrompt(String prompt) {
        this.prompt = prompt;
    }

    public String getResponse() {
        return response;
    }

    public void setResponse(String response) {
        this.response = response;
    }

    public static class QualityCheckRequestBuilder {
        private String requestId;
        private String prompt;
        private String response;

        public QualityCheckRequestBuilder requestId(String requestId) {
            this.requestId = requestId;
            return this;
        }

        public QualityCheckRequestBuilder prompt(String prompt) {
            this.prompt = prompt;
            return this;
        }

        public QualityCheckRequestBuilder response(String response) {
            this.response = response;
            return this;
        }

        public QualityCheckRequest build() {
            return new QualityCheckRequest(requestId, prompt, response);
        }
    }
}
