-- =========================================================================
-- Enterprise AI Guardian - Relational Database Schema (PostgreSQL / H2)
-- Phase 10 Database Layer: Schema, Entities, Relationships, and Indexes
-- =========================================================================

-- 1. Primary Audit Events Table
CREATE TABLE IF NOT EXISTS audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id VARCHAR(255) NOT NULL,
    user_id VARCHAR(255) NOT NULL,
    user_role VARCHAR(50) NOT NULL,
    model VARCHAR(100),
    prompt_category VARCHAR(50),
    action VARCHAR(20) NOT NULL,
    risk_score INTEGER DEFAULT 0,
    risk_level VARCHAR(20),
    tokens_in INTEGER DEFAULT 0,
    tokens_out INTEGER DEFAULT 0,
    cost_usd DOUBLE PRECISION DEFAULT 0.0,
    quality_verdict VARCHAR(20),
    hallucination_score DOUBLE PRECISION DEFAULT 0.0,
    approval_required BOOLEAN DEFAULT FALSE,
    violations_summary TEXT,
    block_reason TEXT,
    prompt TEXT,
    timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    approval_status VARCHAR(20) DEFAULT 'NONE',
    approver VARCHAR(255),
    approval_timestamp TIMESTAMP,
    approval_reason TEXT
);

CREATE INDEX IF NOT EXISTS idx_audit_user ON audit_events(user_id);
CREATE INDEX IF NOT EXISTS idx_audit_action ON audit_events(action);
CREATE INDEX IF NOT EXISTS idx_audit_risk ON audit_events(risk_level);
CREATE INDEX IF NOT EXISTS idx_audit_timestamp ON audit_events(timestamp);
CREATE INDEX IF NOT EXISTS idx_audit_approval ON audit_events(approval_status);
CREATE INDEX IF NOT EXISTS idx_audit_request ON audit_events(request_id);

-- 2. Audit Violations Table (One-to-Many Relationship with audit_events)
CREATE TABLE IF NOT EXISTS audit_violations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    audit_event_id BIGINT NOT NULL,
    violation_type VARCHAR(50) NOT NULL,
    severity VARCHAR(20) NOT NULL,
    description TEXT,
    matched_text TEXT,
    start_index INTEGER,
    end_index INTEGER,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_violations_audit_event FOREIGN KEY (audit_event_id) REFERENCES audit_events(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_viol_audit_event ON audit_violations(audit_event_id);
CREATE INDEX IF NOT EXISTS idx_viol_type ON audit_violations(violation_type);
CREATE INDEX IF NOT EXISTS idx_viol_severity ON audit_violations(severity);

-- 3. Approval Records Table (One-to-One / One-to-Many Relationship with audit_events)
CREATE TABLE IF NOT EXISTS approval_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    audit_event_id BIGINT NOT NULL UNIQUE,
    decision VARCHAR(20) NOT NULL,
    approver VARCHAR(255) NOT NULL,
    reason TEXT,
    reviewed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    notes TEXT,
    CONSTRAINT fk_approvals_audit_event FOREIGN KEY (audit_event_id) REFERENCES audit_events(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_approval_event ON approval_records(audit_event_id);
CREATE INDEX IF NOT EXISTS idx_approval_decision ON approval_records(decision);
CREATE INDEX IF NOT EXISTS idx_approval_approver ON approval_records(approver);
CREATE INDEX IF NOT EXISTS idx_approval_reviewed ON approval_records(reviewed_at);

-- 4. Compliance Snapshots Table (Regulatory Framework Metrics)
CREATE TABLE IF NOT EXISTS compliance_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_date DATE NOT NULL,
    framework VARCHAR(100) NOT NULL,
    total_evaluated BIGINT NOT NULL DEFAULT 0,
    violations_count BIGINT NOT NULL DEFAULT 0,
    compliance_score DOUBLE PRECISION NOT NULL DEFAULT 100.0,
    status VARCHAR(50) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_comp_date ON compliance_snapshots(snapshot_date);
CREATE INDEX IF NOT EXISTS idx_comp_framework ON compliance_snapshots(framework);
CREATE INDEX IF NOT EXISTS idx_comp_status ON compliance_snapshots(status);

-- 5. Model Pricing Table (Dynamic Schedules & Costs)
CREATE TABLE IF NOT EXISTS model_pricing (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_name VARCHAR(100) NOT NULL UNIQUE,
    cost_per_1k_input DOUBLE PRECISION NOT NULL,
    cost_per_1k_output DOUBLE PRECISION NOT NULL,
    active BOOLEAN DEFAULT TRUE,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_pricing_model ON model_pricing(model_name);

